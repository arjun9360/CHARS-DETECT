import test from 'node:test';
import assert from 'node:assert/strict';
import {
  detectFileSignature,
  calculateSha256,
  calculateSimplePerceptualHash,
  inspectC2PAContentCredentials,
  inspectMetadataForensics,
  calculateNoiseAndELA,
  aggregateEvidence
} from '../server/core/forensics.ts';

test('detectFileSignature identifies JPEG magic bytes', () => {
  const jpegHeader = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01]);
  const sig = detectFileSignature(jpegHeader);
  assert.ok(sig);
  assert.equal(sig.mediaType, 'image');
  assert.equal(sig.mimeType, 'image/jpeg');
  assert.equal(sig.extension, 'jpg');
});

test('detectFileSignature identifies PNG magic bytes', () => {
  const pngHeader = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d]);
  const sig = detectFileSignature(pngHeader);
  assert.ok(sig);
  assert.equal(sig.mediaType, 'image');
  assert.equal(sig.mimeType, 'image/png');
});

test('detectFileSignature identifies MP4 video bytes', () => {
  const mp4Header = Buffer.from([0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d]);
  const sig = detectFileSignature(mp4Header);
  assert.ok(sig);
  assert.equal(sig.mediaType, 'video');
  assert.equal(sig.mimeType, 'video/mp4');
});

test('detectFileSignature identifies WAV audio bytes', () => {
  const wavHeader = Buffer.from('RIFF\x24\x00\x00\x00WAVEfmt \x10\x00\x00\x00', 'binary');
  const sig = detectFileSignature(wavHeader);
  assert.ok(sig);
  assert.equal(sig.mediaType, 'audio');
  assert.equal(sig.mimeType, 'audio/wav');
});

test('detectFileSignature rejects unsupported random bytes', () => {
  const garbage = Buffer.from([0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb]);
  const sig = detectFileSignature(garbage);
  assert.equal(sig, null);
});

test('calculateSha256 produces exact cryptographic digest', () => {
  const data = Buffer.from('verification-test-payload-bytes');
  const hash = calculateSha256(data);
  assert.equal(hash.length, 64);
  assert.match(hash, /^[0-9a-f]{64}$/);
});

test('calculateSimplePerceptualHash is deterministic', () => {
  const data1 = Buffer.from('synthetic-image-layer-data-test-1');
  const data2 = Buffer.from('synthetic-image-layer-data-test-1');
  assert.equal(calculateSimplePerceptualHash(data1), calculateSimplePerceptualHash(data2));
});

test('inspectC2PAContentCredentials detects missing credentials cleanly', () => {
  const buf = Buffer.from('Standard raw image pixel data with no cryptographic credentials');
  const result = inspectC2PAContentCredentials(buf);
  assert.equal(result.hasCredentials, false);
  assert.equal(result.status, 'missing');
});

test('inspectC2PAContentCredentials discovers C2PA JUMBF manifests', () => {
  const buf = Buffer.from('Header-prefix-c2pa-jumb-manifest-Leica M11-P Content Credentials-suffix');
  const result = inspectC2PAContentCredentials(buf);
  assert.equal(result.hasCredentials, true);
  assert.equal(result.status, 'valid');
  assert.ok(result.manifestDetails);
  assert.match(result.manifestDetails.claimGenerator, /Leica/);
});

test('inspectMetadataForensics identifies Midjourney signatures', () => {
  const buf = Buffer.from('EXIF data: generated by Midjourney v6 --ar 16:9 --v 6.0');
  const meta = inspectMetadataForensics(buf);
  assert.ok(meta.aiSignaturesFound.length > 0);
  assert.match(meta.aiSignaturesFound[0], /Midjourney/);
});

test('calculateNoiseAndELA handles byte buffers reliably', () => {
  const sampleBuf = Buffer.alloc(16384, 128);
  const ela = calculateNoiseAndELA(sampleBuf);
  assert.ok(ela.score >= 0 && ela.score <= 1);
  assert.ok(Array.isArray(ela.findings));
});

test('aggregateEvidence produces responsible non-misleading assessments', () => {
  // Case A: Valid C2PA with clean metadata
  const assessmentA = aggregateEvidence({
    mediaType: 'image',
    c2pa: {
      hasCredentials: true,
      status: 'valid',
      manifestDetails: {
        claimGenerator: 'Truepic Lens',
        format: 'C2PA v1.4',
        signatureStatus: 'valid',
        assertions: [],
        thumbnailFound: false
      },
      notes: 'Valid'
    },
    metadata: {
      hasExif: true,
      aiSignaturesFound: [],
      anomalies: [],
      rawTags: {}
    },
    ela: {
      score: 0.1,
      compressionUniformity: 'uniform',
      frequencyHighDiscontinuity: false,
      findings: ['Uniform profile']
    },
    aiDetections: [{ model: 'ResNet50-Forensics', score: 0.04, findingsDetected: false }]
  });
  assert.equal(assessmentA.overallStatus, 'Evidence supports recorded provenance');

  // Case B: AI generated with Midjourney metadata and detected artifact
  const assessmentB = aggregateEvidence({
    mediaType: 'image',
    c2pa: { hasCredentials: false, status: 'missing', notes: 'Missing' },
    metadata: {
      hasExif: false,
      aiSignaturesFound: ['Midjourney Synthetic Generation Signature'],
      anomalies: ['Missing EXIF'],
      rawTags: {}
    },
    ela: {
      score: 0.85,
      compressionUniformity: 'inconsistent',
      frequencyHighDiscontinuity: true,
      findings: ['Inconsistent block error level']
    },
    aiDetections: [{ model: 'ViT-Deepfake', score: 0.94, findingsDetected: true }]
  });
  assert.equal(assessmentB.overallStatus, 'Potential manipulation indicators detected');
});

test('cleanDisplayName strips all designation titles and parentheses', async () => {
  const { cleanDisplayName } = await import('../types/client.ts');
  assert.equal(cleanDisplayName('Arjun R. (Principal Security Officer)'), 'Arjun R.');
  assert.equal(cleanDisplayName('Jane Doe (Senior Cyber Analyst)'), 'Jane Doe');
  assert.equal(cleanDisplayName('Arjun R. - Lead Forensic Specialist'), 'Arjun R.');
  assert.equal(cleanDisplayName('Sarah Connor, Senior Analyst'), 'Sarah Connor');
  assert.equal(cleanDisplayName('Alex Morgan | Chief Investigator'), 'Alex Morgan');
  assert.equal(cleanDisplayName('Alex Morgan'), 'Alex Morgan');
  assert.equal(cleanDisplayName(''), '');
  assert.equal(cleanDisplayName(null), '');
  assert.equal(cleanDisplayName(undefined), '');
});

